// netlify/functions/start-transcription.mjs
// Prompt Sandbox — video/audio-to-transcript feature. Submits a Firebase
// Storage download URL to AssemblyAI's async transcription API and
// returns the resulting job ID. Deliberately does NOT proxy the file
// itself through this function — the client uploads directly to Firebase
// Storage first (see sandboxLibrary.js's uploadTranscriptSource), and
// AssemblyAI fetches the audio from that URL server-side on their end.
// This keeps the function body tiny and fast regardless of file size,
// and sidesteps Netlify's 26-second synchronous timeout (already a known,
// unresolved limitation elsewhere in this app — see Handoff #26) since
// this call only has to submit a job, not wait for transcription to
// finish. Poll check-transcription.mjs for the actual result.
//
// Auth:       Manager/Administrator only, same gate as the rest of the
//             Prompt Sandbox (generate-sandbox-text.mjs).
// Rate limit: NOT wired into checkAndIncrementRateLimit — that counter
//             tracks Claude API calls specifically (a token-cost meter),
//             and this hits a separate service with its own per-minute
//             cost model, so it gets its own counter below
//             (checkAndIncrementTranscriptionLimit) rather than muddying
//             what the Claude counter represents. FIXED this session —
//             this was flagged as a known gap across several earlier
//             handoffs (no daily cap on transcription usage) and never
//             actually built until now. Per-user AND sitewide caps, same
//             two-tier shape as public-storm-regenerate.mjs's breakers,
//             built as a transaction from the start rather than a
//             read-then-write (see that file's own fix this session for
//             why a plain read+write here would be a real race/cost risk
//             under concurrent requests).
//
// audioUrl validation (new — added alongside Sandbox's "paste a link"
// input): this function used to only ever receive a Firebase Storage URL
// it had generated itself moments earlier. Now that a manager can paste
// an arbitrary URL directly, this function is doing a server-side fetch
// of user-supplied input, which is a real SSRF surface, not just a cost
// concern — a pasted URL could otherwise point at an internal service or
// a cloud metadata endpoint and this server would dutifully fetch it.
// assertPublicHttpsMediaUrl() below requires https, resolves the
// hostname and rejects private/loopback/link-local addresses, and does a
// HEAD request to confirm the target actually looks like a video/audio
// file before it's ever handed to AssemblyAI. This runs for every
// audioUrl regardless of source (including the Firebase Storage flow) —
// cheap, and it means the two paths share one trust boundary instead of
// the pasted-URL path being a weaker copy of the upload path.

import admin from "firebase-admin";
import { readFileSync } from "node:fs";
import dns from "node:dns/promises";
import net from "node:net";

const MAX_TRANSCRIPT_SOURCE_MB = 500; // mirrors sandboxLibrary.js's MAX_TRANSCRIPT_SOURCE_MB — kept in sync manually since this file can't import from src/

// Trusted Firebase Storage download-URL host — generated by this app's own
// upload flow (sandboxLibrary.js), so the content-type HEAD check below is
// skipped for it (the client already validated file.type before upload).
// The SSRF/protocol checks still run for every host, this one included.
const TRUSTED_MEDIA_HOSTS = new Set(["firebasestorage.googleapis.com"]);

function isPrivateOrReservedIp(ip) {
  if (net.isIPv4(ip)) {
    const [a, b] = ip.split(".").map(Number);
    if (a === 10) return true;                          // 10.0.0.0/8
    if (a === 127) return true;                          // loopback
    if (a === 0) return true;                             // "this network"
    if (a === 169 && b === 254) return true;              // link-local incl. cloud metadata (169.254.169.254)
    if (a === 172 && b >= 16 && b <= 31) return true;      // 172.16.0.0/12
    if (a === 192 && b === 168) return true;               // 192.168.0.0/16
    if (a === 100 && b >= 64 && b <= 127) return true;     // 100.64.0.0/10 (CGNAT) — extra caution
    return false;
  }
  const lower = ip.toLowerCase();
  if (lower === "::1") return true;                        // loopback
  if (lower.startsWith("fe80:")) return true;               // link-local
  if (lower.startsWith("fc") || lower.startsWith("fd")) return true; // unique local fc00::/7
  if (lower.startsWith("::ffff:")) return isPrivateOrReservedIp(lower.split(":").pop()); // IPv4-mapped
  return false;
}

async function assertPublicHttpsMediaUrl(rawUrl) {
  let parsed;
  try {
    parsed = new URL(rawUrl);
  } catch {
    throw new Error("That doesn't look like a valid URL.");
  }
  if (parsed.protocol !== "https:") {
    throw new Error("Please use an https:// link.");
  }

  let addresses;
  try {
    addresses = await dns.lookup(parsed.hostname, { all: true });
  } catch {
    throw new Error("Couldn't resolve that URL's host.");
  }
  if (addresses.some(({ address }) => isPrivateOrReservedIp(address))) {
    throw new Error("That link points to a restricted address and can't be used.");
  }

  if (TRUSTED_MEDIA_HOSTS.has(parsed.hostname)) return; // our own upload flow already validated the file client-side

  let headRes;
  try {
    headRes = await fetch(rawUrl, { method: "HEAD" });
  } catch {
    throw new Error("Couldn't reach that URL to confirm it's a video/audio file.");
  }
  const contentType = headRes.headers.get("content-type") || "";
  if (!contentType.startsWith("video/") && !contentType.startsWith("audio/")) {
    throw new Error("That link doesn't appear to point directly to a video or audio file — check it's a direct file link, not a webpage.");
  }
  const contentLength = headRes.headers.get("content-length");
  if (contentLength && Number(contentLength) > MAX_TRANSCRIPT_SOURCE_MB * 1024 * 1024) {
    throw new Error(`That file is larger than the ${MAX_TRANSCRIPT_SOURCE_MB}MB limit.`);
  }
}

const TRANSCRIPTION_LIMITS = { perUser: 20, sitewide: 100 }; // submissions/day — not duration-based, but bounds worst case to a known multiple of the existing 500MB per-file cap rather than leaving it fully open

function todayUTC() {
  return new Date().toISOString().slice(0, 10);
}

// Atomic (transaction-based) check-and-increment, same reasoning as the
// fix applied to rateLimitHelper.mjs and public-storm-regenerate.mjs this
// session — built this way from the start here since a plain read+write
// would carry the identical concurrent-request race.
async function checkAndIncrementTranscriptionLimit(app, uid) {
  const db = admin.firestore(app);
  const today = todayUTC();
  const userRef = db.doc(`transcriptionLimits/user_${today}_${uid}`);
  const sitewideRef = db.doc(`transcriptionLimits/sitewide_${today}`);

  return db.runTransaction(async (tx) => {
    const [userSnap, sitewideSnap] = await Promise.all([tx.get(userRef), tx.get(sitewideRef)]);
    const userCount = userSnap.exists ? (userSnap.data().count || 0) : 0;
    const sitewideCount = sitewideSnap.exists ? (sitewideSnap.data().count || 0) : 0;

    if (userCount >= TRANSCRIPTION_LIMITS.perUser) {
      return { blocked: true, message: `You've reached today's limit of ${TRANSCRIPTION_LIMITS.perUser} transcriptions. Resets at midnight UTC.` };
    }
    if (sitewideCount >= TRANSCRIPTION_LIMITS.sitewide) {
      return { blocked: true, message: `The site-wide daily transcription limit (${TRANSCRIPTION_LIMITS.sitewide}) has been reached. Resets at midnight UTC. Contact an administrator if this needs to be raised.` };
    }

    tx.set(userRef, { count: admin.firestore.FieldValue.increment(1) }, { merge: true });
    tx.set(sitewideRef, { count: admin.firestore.FieldValue.increment(1) }, { merge: true });
    return { blocked: false };
  });
}

const ALLOWED_ORIGINS = [
  "https://arizonacoalition.net",
  "https://az-coalition-2026-election.netlify.app",
];
function corsHeaders(req) {
  const origin = req.headers.get("origin");
  const allowOrigin = ALLOWED_ORIGINS.includes(origin) ? origin : ALLOWED_ORIGINS[0];
  return { "Content-Type": "application/json", "Access-Control-Allow-Origin": allowOrigin };
}

function getAdminApp() {
  if (admin.apps.length) return admin.app();
  let serviceAccount;
  try {
    serviceAccount = JSON.parse(readFileSync(new URL("./firebase-service-account.json", import.meta.url), "utf8"));
  } catch {
    throw new Error("firebase-service-account.json not found — run `npm run build` to regenerate via scripts/inject-secrets.mjs.");
  }
  return admin.initializeApp({ credential: admin.credential.cert(serviceAccount) });
}

async function requireManagerOrAdmin(app, idToken) {
  if (!idToken) throw new Error("unauthenticated");
  const decoded = await admin.auth(app).verifyIdToken(idToken);
  const snap = await admin.firestore(app).doc(`users/${decoded.uid}`).get();
  const role = snap.exists ? (snap.data().role || "user") : "user";
  if (role !== "manager" && role !== "administrator") {
    throw new Error("forbidden");
  }
  return decoded.uid;
}

export default async function (req) {
  if (req.method === "OPTIONS") {
    return new Response("", {
      status: 200,
      headers: { ...corsHeaders(req), "Access-Control-Allow-Headers": "Content-Type, Authorization", "Access-Control-Allow-Methods": "POST, OPTIONS" },
    });
  }
  if (req.method !== "POST") return new Response("Method Not Allowed", { status: 405 });

  let app;
  try { app = getAdminApp(); } catch (err) {
    console.error("[start-transcription] admin init:", err.message);
    return new Response(JSON.stringify({ error: "Server configuration error." }), { status: 500, headers: corsHeaders(req) });
  }

  const authHeader = req.headers.get("authorization") || "";
  const headerToken = authHeader.startsWith("Bearer ") ? authHeader.slice(7) : null;

  try {
    const body = await req.json();
    const idToken = headerToken || body.idToken;

    let uid;
    try {
      uid = await requireManagerOrAdmin(app, idToken);
    } catch (err) {
      const status = err.message === "forbidden" ? 403 : 401;
      const msg = err.message === "forbidden"
        ? "Video/audio transcription is limited to Managers and Administrators."
        : "You must be signed in to use this tool.";
      return new Response(JSON.stringify({ error: msg }), { status, headers: corsHeaders(req) });
    }

    const limitResult = await checkAndIncrementTranscriptionLimit(app, uid);
    if (limitResult.blocked) {
      return new Response(JSON.stringify({ error: limitResult.message }), { status: 429, headers: corsHeaders(req) });
    }

    const { audioUrl } = body;
    if (!audioUrl || typeof audioUrl !== "string") {
      return new Response(JSON.stringify({ error: "Missing audioUrl." }), { status: 400, headers: corsHeaders(req) });
    }

    try {
      await assertPublicHttpsMediaUrl(audioUrl);
    } catch (err) {
      return new Response(JSON.stringify({ error: err.message }), { status: 400, headers: corsHeaders(req) });
    }

    if (!process.env.ASSEMBLYAI_API_KEY) {
      return new Response(JSON.stringify({ error: "Transcription isn't configured yet — an Administrator needs to add ASSEMBLYAI_API_KEY in Netlify's environment variables." }), { status: 500, headers: corsHeaders(req) });
    }

    const response = await fetch("https://api.assemblyai.com/v2/transcript", {
      method: "POST",
      headers: {
        "authorization": process.env.ASSEMBLYAI_API_KEY,
        "content-type": "application/json",
      },
      body: JSON.stringify({ audio_url: audioUrl }),
    });

    const data = await response.json();
    if (!response.ok) {
      console.error("[start-transcription] AssemblyAI error:", data);
      return new Response(JSON.stringify({ error: data.error || "Transcription service rejected the request." }), { status: 502, headers: corsHeaders(req) });
    }

    return new Response(JSON.stringify({ id: data.id }), { status: 200, headers: corsHeaders(req) });
  } catch (err) {
    console.error("[start-transcription] FAILED:", err.message);
    return new Response(JSON.stringify({ error: err.message }), { status: 500, headers: corsHeaders(req) });
  }
}
